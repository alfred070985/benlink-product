def classify(text, brand_strip=True):
    """中文品名/类目名 → 大类。返回 dict。

    分词理解：先剥品牌词，再按关键词由长到短在文本里找命中（等价于
    "在原串中做品类词的分词切分"），最长命中即归类，避免短词误伤。
    """
    s = str(text or "")
    s = re.sub(r"[\s\*x×（）()【】\[\]/\\]", " ", s)
    if brand_strip:
        for b in BRAND_STRIP:
            s = s.replace(b, " ")
    for w in _SORTED_WORDS:
        if w in s:
            cid = _WORD2CAT[w]
            return {"cat": cid, "name": CATEGORY_KEYWORDS[cid][0],
                    "matched": w, "combo": is_combo(text),
                    "brand_stripped": brand_strip}
    return {"cat": 0, "name": "其他", "matched": "", "combo": is_combo(text),
            "brand_stripped": brand_strip}


